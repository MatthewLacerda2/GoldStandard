// @vitest-environment node
// `tools/markers.py` leaves every frontend `.ts`/`.tsx` file to this rule
// (its `LAYER_LINTED`), and the root completeness test takes that on trust.
// This holds ESLint to it: a new entry in `ignores`, or an override turning
// the rule off, would otherwise drop files from every marker check unseen.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { ESLint } from "eslint";
import { describe, expect, it } from "vitest";

const FRONTEND = join(import.meta.dirname, "..");
const RULE = "local/no-marker-comment";
// ESLint reports a configured rule's severity as a number.
const SEVERITY: Record<string, string> = { 0: "off", 1: "warn", 2: "error" };

// The tracked files ESLint does not read, each with its reason. Each one is
// in `tools/markers.py`'s `NOT_READ` too, so no check is expected to read it.
const UNREAD: Record<string, string> = {
  "src/routeTree.gen.ts": "generated by the router plugin, never edited",
};

// `*` in a git pathspec crosses folders, so these match at any depth.
const tracked = execFileSync("git", ["ls-files", "-z", "--", "*.ts", "*.tsx"], {
  cwd: FRONTEND,
  encoding: "utf8",
})
  .split("\0")
  .filter(Boolean);

const eslint = new ESLint({ cwd: FRONTEND });

/** How ESLint treats the rule in `path`: "error" is the only passing answer. */
async function ruleIn(path: string): Promise<string> {
  if (await eslint.isPathIgnored(path)) return "ignored";
  const config = (await eslint.calculateConfigForFile(path)) as
    { rules?: Record<string, unknown> } | undefined;
  if (!config) return "matched by no config";
  const [severity] = [config.rules?.[RULE] ?? "absent"].flat();
  return SEVERITY[String(severity)] ?? String(severity);
}

const notAtError = Object.fromEntries(
  (
    await Promise.all(tracked.map(async (path) => [path, await ruleIn(path)]))
  ).filter(([, state]) => state !== "error"),
);

describe(`${RULE} scope`, () => {
  it("reads the tracked frontend sources at all", () => {
    expect(tracked).toContain("eslint.config.ts");
    expect(tracked).toContain("src/main.tsx");
  });

  it("is an error in every tracked .ts/.tsx file but the named exceptions", () => {
    const expected = Object.fromEntries(
      Object.keys(UNREAD).map((path) => [path, "ignored"]),
    );
    expect(notAtError).toEqual(expected);
  });

  it("names each exception in tools/markers.py's NOT_READ", () => {
    const markers = readFileSync(join(FRONTEND, "../tools/markers.py"), "utf8");
    const notRead = /^NOT_READ = \(([\s\S]*?)^\)/m.exec(markers)?.[1] ?? "";
    for (const path of Object.keys(UNREAD)) {
      expect(notRead).toContain(`"frontend/${path}"`);
    }
  });
});
